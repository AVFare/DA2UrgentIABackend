-- Transactional Outbox (ADR-12): cada mensaje que ticket-service tiene que publicar en RabbitMQ
-- se guarda aca en la misma transaccion que el ticket. Si la transaccion se deshace, no queda
-- nada para publicar; si confirma, el mensaje queda guardado aunque el broker este caido.
-- PublicadorDelOutbox lee las filas pendientes en orden (id), las publica con confirmacion
-- del broker y recien ahi completa publicado_en.
CREATE TABLE outbox (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       UUID                     NOT NULL UNIQUE,
    event_type     VARCHAR(60)              NOT NULL,
    exchange       VARCHAR(100)             NOT NULL,
    routing_key    VARCHAR(100)             NOT NULL,
    correlation_id VARCHAR(100)             NOT NULL,
    ticket_id      UUID                     NOT NULL,
    cuerpo         VARCHAR(8000)            NOT NULL,
    ocurrido_en    TIMESTAMP WITH TIME ZONE NOT NULL,
    creado_en      TIMESTAMP WITH TIME ZONE NOT NULL,
    publicado_en   TIMESTAMP WITH TIME ZONE,
    intentos       INT                      NOT NULL DEFAULT 0,
    ultimo_error   VARCHAR(500)
);

-- El publicador busca las pendientes (publicado_en null) en orden de id.
CREATE INDEX idx_outbox_pendientes ON outbox (publicado_en, id);
